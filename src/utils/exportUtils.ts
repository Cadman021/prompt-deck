import { DbService, BenchmarkResult } from '../services/dbService';

interface CurrentBenchmarkData {
  prompt: string;
  results: BenchmarkResult[];
  /** Live thinking traces (bench only — history never stored them). */
  reasoningByModel?: Record<string, string>;
}

function formatTpsCell(r: BenchmarkResult): string {
  if (!r.tps) return 'N/A';
  const value = r.tps.toFixed(2);
  return r.tpsEstimated ? `~${value} tok/s (estimated)` : `**${value}** tok/s`;
}

function formatTokensCell(r: BenchmarkResult): string {
  if (r.promptTokens == null && r.completionTokens == null) return 'N/A';
  const p = r.promptTokens ?? '?';
  const c = r.completionTokens ?? '?';
  return `${p} in / ${c} out`;
}

function formatCostCell(r: BenchmarkResult): string {
  if (r.costUsd == null) return 'N/A';
  return r.costUsd < 0.01 ? `$${r.costUsd.toFixed(5)}` : `$${r.costUsd.toFixed(4)}`;
}

export const generateMarkdownReport = (data: CurrentBenchmarkData): string => {
  const tableHeader = `| Metric | ${data.results.map((r) => r.model).join(' | ')} |`;
  const tableDivider = `| :--- | ${data.results.map(() => ':---').join(' | ')} |`;
  const tpsRow = `| **Tokens / Sec (TPS)** | ${data.results.map(formatTpsCell).join(' | ')} |`;
  const ttftRow = `| **Time To First Token (TTFT)** | ${data.results
    .map((r) => (r.ttft ? `${r.ttft} ms` : 'N/A'))
    .join(' | ')} |`;
  const hasTokens = data.results.some((r) => r.promptTokens != null || r.completionTokens != null);
  const tokensRow = hasTokens
    ? `| **Tokens (in / out)** | ${data.results.map(formatTokensCell).join(' | ')} |`
    : '';
  const hasCost = data.results.some((r) => r.costUsd != null);
  const costRow = hasCost
    ? `| **Cost (USD)** | ${data.results.map(formatCostCell).join(' | ')} |`
    : '';

  const outputSections = data.results
    .map((r, i) => {
      // Stored reasoning wins (history reloads); live runs also pass it via
      // reasoningByModel for the current session.
      const thinking = (r.reasoning || data.reasoningByModel?.[r.model] || '').trim();
      const thinkingSection = thinking
        ? `\n<details>\n<summary>Thinking</summary>\n\n${thinking}\n\n</details>\n`
        : '';
      return `
### 🤖 Model ${i + 1}: \`${r.model}\`
${thinkingSection}${r.output || '_No output_'}
`;
    })
    .join('\n---\n');

  const hasEstimated = data.results.some((r) => r.tpsEstimated);
  const footnote = hasEstimated
    ? '\n> ~ = estimated TPS (server did not report token usage).\n'
    : '';

  const summaryRows = [tpsRow, ttftRow];
  if (tokensRow) summaryRows.push(tokensRow);
  if (costRow) summaryRows.push(costRow);

  return `# 📊 PromptDeck Benchmark Report

**Prompt:**
> ${data.prompt}

## ⚡ Performance Summary
${tableHeader}
${tableDivider}
${summaryRows.join('\n')}
${footnote}
---

## 📝 Model Outputs
${outputSections}

---
*Generated by PromptDeck*
`;
};

export const copyHistoryAsJson = async (): Promise<'ok' | 'empty' | 'error'> => {
  try {
    const history = await DbService.getHistory();

    if (!history || history.length === 0) {
      return 'empty';
    }

    const jsonString = JSON.stringify(history, null, 2);
    await navigator.clipboard.writeText(jsonString);
    return 'ok';
  } catch (error) {
    console.error('Failed to copy history JSON:', error);
    return 'error';
  }
};

function csvEscape(value: string | number | null | undefined): string {
  let s = value == null ? '' : String(value);
  // CSV injection guard: cells starting with = + - @ (or tab/CR) can execute
  // as formulas when opened in Excel. A leading single quote is Excel's
  // text-marker and stays invisible in the cell.
  if (/^[=+\-@\t\r]/.test(s)) s = `'${s}`;
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

/**
 * Exports the full benchmark history as a CSV file (one row per model result).
 * Downloads via a Blob URL so it works in both Tauri and plain web builds.
 * Returns false when there is nothing to export.
 */
export const exportHistoryAsCsv = async (): Promise<boolean> => {
  try {
    // limit 0 = no LIMIT: a "full history" export must not stop at 50 rows.
    const history = await DbService.getHistory(0);
    if (!history || history.length === 0) return false;

    const header = [
      'run_id',
      'created_at',
      'prompt',
      'model',
      'tps',
      'tps_estimated',
      'ttft_ms',
      'prompt_tokens',
      'completion_tokens',
      'cost_usd',
      'winner_model',
      'output',
    ];
    const lines = [header.join(',')];
    for (const record of history) {
      for (const r of record.results) {
        lines.push(
          [
            csvEscape(record.id),
            csvEscape(record.created_at),
            csvEscape(record.prompt),
            csvEscape(r.model),
            csvEscape(r.tps),
            csvEscape(r.tpsEstimated ? 1 : 0),
            csvEscape(r.ttft),
            csvEscape(r.promptTokens),
            csvEscape(r.completionTokens),
            csvEscape(r.costUsd),
            csvEscape(record.winnerModel),
            csvEscape(r.output),
          ].join(',')
        );
      }
    }

    // Leading BOM so Excel detects UTF-8 (Persian/Chinese/Russian text).
    const blob = new Blob(['\uFEFF' + lines.join('\n')], { type: 'text/csv;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `promptdeck-history-${Date.now()}.csv`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);
    return true;
  } catch (error) {
    console.error('Failed to export history CSV:', error);
    return false;
  }
};
